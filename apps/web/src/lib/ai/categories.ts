/**
 * Fetch all active categories from Supabase (with DB keywords for zero-drift resolution)
 */
export async function fetchActiveCategories(): Promise<ServiceCategoryRecord[]> {
  const res = await supabaseAdminFetch<ServiceCategoryRecord[]>(
    "/rest/v1/service_categories?select=id,parent_id,name,slug,description,keywords,is_active&is_active=eq.true&deleted_at=is.null&order=display_order.asc"
  );
  if (res.ok && Array.isArray(res.data)) {
    return res.data;
  }
  return [];
}

/**
 * Validates candidate category generated by AI or heuristic matching against database records.
 */
export async function validateAndResolveCategory(
  candidate: string | { id?: string; name?: string; slug?: string }
): Promise<AIAssistantCategoryRecommendation | null> {
  const categories = await fetchActiveCategories();
  if (categories.length === 0) return null;

  // 1. Direct ID match
  if (typeof candidate === "object" && candidate.id) {
    const matched = categories.find((c) => c.id === candidate.id);
    if (matched) {
      return {
        categoryId: matched.id,
        categoryName: matched.name,
        categorySlug: matched.slug,
        confidence: "high",
        reasoning: `Matches accredited database service category "${matched.name}".`,
      };
    }
  }

  // 2. Direct slug or name match
  const candidateStr = (
    typeof candidate === "string" ? candidate : candidate.slug || candidate.name || ""
  )
    .trim()
    .toLowerCase();

  const directMatch = categories.find(
    (c) =>
      c.slug.toLowerCase() === candidateStr ||
      c.name.toLowerCase() === candidateStr
  );

  if (directMatch) {
    return {
      categoryId: directMatch.id,
      categoryName: directMatch.name,
      categorySlug: directMatch.slug,
      confidence: "high",
      reasoning: `Direct match for "${directMatch.name}".`,
    };
  }

  // 3. Database keywords match
  const dbKeywordMatch = categories.find((c) =>
    Array.isArray(c.keywords) &&
    c.keywords.some((kw) => kw.trim().length > 0 && candidateStr.includes(kw.toLowerCase()))
  );
  if (dbKeywordMatch) {
    return {
      categoryId: dbKeywordMatch.id,
      categoryName: dbKeywordMatch.name,
      categorySlug: dbKeywordMatch.slug,
      confidence: "high",
      reasoning: `Matched database catalogue keywords for accredited trade category "${dbKeywordMatch.name}".`,
    };
  }

  // 4. Synonym / Keyword Resolution
  for (const [keyword, targetSlug] of Object.entries(SYNONYM_MAP)) {
    if (candidateStr.includes(keyword)) {
      const match = categories.find((c) => c.slug === targetSlug);
      if (match) {
        return {
          categoryId: match.id,
          categoryName: match.name,
          categorySlug: match.slug,
          confidence: "high",
          reasoning: `Matched via diagnostic keyword "${keyword}" to accredited trade category "${match.name}".`,
        };
      }
    }
  }

  // 5. Fuzzy Substring Match
  const partialMatch = categories.find((c) => {
    const firstWord = c.name.toLowerCase().split(" ")[0] || "";
    return (firstWord.length > 2 && candidateStr.includes(firstWord)) || c.slug.includes(candidateStr);
  });

  if (partialMatch) {
    return {
      categoryId: partialMatch.id,
      categoryName: partialMatch.name,
      categorySlug: partialMatch.slug,
      confidence: "medium",
      reasoning: `Closest verified marketplace category: "${partialMatch.name}".`,
    };
  }

  return null;
}
